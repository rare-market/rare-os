// Generates src/kit/lucide.rs from lucide-react (the web launcher's icon set, same version).
// Usage: node tools/lucide.mjs <launcher/node_modules> > src/kit/lucide.rs
import { readFileSync } from "node:fs";

const nm = process.argv[2];
const names = [
  "play", "wifi", "wifi-off", "layout-grid", "search", "plus", "folder", "check", "wallet", "sun", "volume-2", "moon",
  "power", "rotate-ccw", "zap", "bell-off", "bluetooth", "plane", "camera", "video", "images", "settings",
  "chevron-down", "battery", "battery-charging", "battery-full", "battery-low", "battery-medium", "monitor", "eye",
  "arrow-right", "store", "x", "badge-check", "users", "gamepad-2", "tv", "download", "cloud",
  // the wallet's set (was screens/wallet/icons.rs)
  "arrow-down-left", "arrow-left-right", "arrow-right-left", "arrow-up-right", "chevron-up", "copy", "external-link",
  "file-text", "fingerprint", "history", "image", "key-round", "lock", "pencil", "plug", "repeat", "shield-alert",
  "shield-check", "smartphone", "trash-2", "triangle-alert", "usb", "user-plus",
  // the rest of the web launcher's lucide imports, and what the native screens draw where the web has art
  "rocket", "dices", "swords", "arrow-down-up", "shield", "bell", "user", "chevron-left", "chevron-right", "info",
  "refresh-cw", "trophy", "share-2", "log-out", "star", "heart", "shopping-cart", "tag", "list", "clock",
  "circle-alert", "sparkles", "keyboard", "gift", "headphones", "message-circle", "send", "sliders-horizontal",
  "hard-drive", "cpu", "globe", "link", "qr-code", "coins", "chart-line", "trending-up", "trending-down",
  "activity", "package", "layers", "user-round", "log-in", "mail", "minus", "arrow-left", "arrow-up", "arrow-down",
  "ellipsis", "circle-check", "loader-circle", "upload", "film", "music", "app-window", "blocks", "ticket", "flame", "terminal",
];
// lucide renamed a few; the launcher keeps the old names
const files = { fingerprint: "fingerprint-pattern" };
const ver = JSON.parse(readFileSync(`${nm}/lucide-react/package.json`, "utf8")).version;
let out = `//! lucide ${ver} icons (ISC), generated by tools/lucide.mjs from the web launcher's lucide-react.\n`;
out += `//! Each entry is the SVG body for a 24x24 viewBox, drawn with stroke=currentColor.\n\n`;
out += `pub fn body(name: &str) -> Option<&'static str> {\n    Some(match name {\n`;
for (const n of names) {
  // an alias file re-exports another icon: follow it
  let file = files[n] ?? n;
  for (let m; (m = /export \{ default \} from '\.\/([a-z0-9-]+)\.mjs'/.exec(readFileSync(`${nm}/lucide-react/dist/esm/icons/${file}.mjs`, "utf8"))); ) file = m[1];
  const { __iconData } = await import(`${nm}/lucide-react/dist/esm/icons/${file}.mjs`);
  const node = __iconData.node;
  const attrs = (a) => Object.entries(a).filter(([k]) => k !== "key").map(([k, v]) => `${k}="${v}"`).join(" ");
  const body = node.map(([tag, a]) => `<${tag} ${attrs(a)}/>`).join("");
  out += `        ${JSON.stringify(n)} => r##"${body}"##,\n`;
}
out += `        _ => return None,\n    })\n}\n`;
process.stdout.write(out);

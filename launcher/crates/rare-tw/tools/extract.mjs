#!/usr/bin/env node
// Extracts every Tailwind class string from launcher/src into the rare-tw corpus.
//
//   node launcher/crates/rare-tw/tools/extract.mjs        (needs launcher/node_modules: npm ci in launcher/)
//
// Writes, under launcher/crates/rare-tw/corpus/:
//   strings.tsv  every class string (static parts of string and template literals whose tokens are
//                all classes), deduplicated: uses <TAB> first location <TAB> classes
//   classes.tsv  every distinct class: uses <TAB> class <TAB> Tailwind's sort key <TAB> its CSS (one line)
//                (sort key = the property-order indices and declaration count Tailwind orders rules by,
//                `order,order;count`, so the Rust cascade can be checked against Tailwind's)
//   dynamic.tsv  class tokens glued to a template expression (`text-${x}`): location <TAB> fragment
//   COVERAGE.md  the report (regenerated by `cargo test -p rare-tw` too, with the Rust side's verdict)
//
// Tailwind itself is the oracle: a token is a utility when Tailwind v4 (the launcher's own version,
// loaded with app.css) compiles it to CSS. Custom classes are the class selectors app.css defines.
// The oxide scanner (what Tailwind scans at build time) cross-checks that no utility it would
// generate is missing from the corpus.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const here = path.dirname(fileURLToPath(import.meta.url));
const crate = path.resolve(here, "..");
const launcher = path.resolve(crate, "../..");
const srcDir = path.join(launcher, "src");
const appCss = path.join(srcDir, "styles/app.css");
const out = path.join(crate, "corpus");

const require = createRequire(path.join(launcher, "package.json"));
const ts = require("typescript");
const { __unstable__loadDesignSystem } = await import(require.resolve("@tailwindcss/node"));
const { Scanner } = require("@tailwindcss/oxide");

const css = fs.readFileSync(appCss, "utf8");
const ds = await __unstable__loadDesignSystem(css, { base: path.dirname(appCss) });

// Class selectors app.css defines (tile, btn, strip-tile, num, rise ...), minus Tailwind's own
// (animate-*) that it only references.
const custom = new Set();
// index.html's inline <style> (the boot splash) defines classes too.
const indexCss = [...fs.readFileSync(path.join(launcher, "index.html"), "utf8").matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)].map((m) => m[1]).join("\n");
for (const block of (css + "\n" + indexCss).replace(/\/\*[\s\S]*?\*\//g, "").matchAll(/([^{}]+)\{/g)) {
  const sel = block[1];
  if (/^\s*@/.test(sel)) continue;
  for (const m of sel.matchAll(/\.([a-zA-Z][\w-]*)/g)) if (!/^animate-/.test(m[1])) custom.add(m[1]);
}

const files = [];
(function walk(d) {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, e.name);
    if (e.isDirectory()) walk(p);
    else if (/\.(tsx?|mts)$/.test(e.name) && !/\.test\.tsx?$/.test(e.name) && !e.name.endsWith(".d.ts")) files.push(p);
  }
})(srcDir);
files.sort();

const CTX_CALL = new Set(["cn", "clsx", "cx", "classNames", "twMerge"]);
const CTX_NAME = /class|^cls$|Cls$|VARIANT|SIZES|^BASE$|^round$|^small$|^big$|^tone|Tone$|^ring$|^chip|^pill|^cell|^col|Cols?$|^style$/i;

function contextOf(node) {
  for (let p = node.parent, depth = 0; p && depth < 12; p = p.parent, depth++) {
    if (ts.isJsxAttribute(p)) return /^(className|class)$/.test(p.name.getText());
    if (ts.isCallExpression(p)) {
      const callee = p.expression.getText();
      if (CTX_CALL.has(callee)) return true;
    }
    if ((ts.isVariableDeclaration(p) || ts.isPropertyAssignment(p) || ts.isPropertyDeclaration(p) || ts.isParameter(p)) && p.name && CTX_NAME.test(p.name.getText())) return true;
    if (ts.isBlock(p) || ts.isSourceFile(p)) return false;
  }
  return false;
}

// Every static literal fragment: { file, line, text, open: [leftGlued, rightGlued], ctx }
const frags = [];
for (const f of files) {
  const text = fs.readFileSync(f, "utf8");
  const sf = ts.createSourceFile(f, text, ts.ScriptTarget.Latest, true, f.endsWith("x") ? ts.ScriptKind.TSX : ts.ScriptKind.TS);
  const rel = path.relative(launcher, f);
  const push = (node, t, left, right) => {
    const line = sf.getLineAndCharacterOfPosition(node.getStart(sf)).line + 1;
    frags.push({ file: rel, line, text: t, left, right, ctx: contextOf(node) });
  };
  (function visit(n) {
    if (ts.isImportDeclaration(n) || ts.isExportDeclaration(n)) return;
    if (ts.isStringLiteral(n) || ts.isNoSubstitutionTemplateLiteral(n)) push(n, n.text, false, false);
    else if (ts.isTemplateExpression(n)) {
      push(n.head, n.head.text, false, true);
      n.templateSpans.forEach((s, i) => push(s.literal, s.literal.text, true, i < n.templateSpans.length - 1));
    }
    ts.forEachChild(n, visit);
  })(sf);
}

// Split fragments into whole tokens and glued (dynamic) ones.
const allTokens = new Set();
for (const fr of frags) {
  const t = fr.text;
  const toks = t.split(/\s+/).filter(Boolean);
  const glueL = fr.left && toks.length && !/^\s/.test(t);
  const glueR = fr.right && toks.length && !/\s$/.test(t);
  fr.dyn = [];
  if (glueR) fr.dyn.push(toks.pop() + "${}");
  if (glueL && toks.length) fr.dyn.unshift("${}" + toks.shift());
  else if (glueL && fr.dyn.length) fr.dyn[0] = "${}" + fr.dyn[0];
  fr.toks = toks;
  for (const k of toks) if (k.length < 600) allTokens.add(k);
}

const list = [...allTokens];
const cssOut = ds.candidatesToCss(list);
const utilCss = new Map();
list.forEach((k, i) => {
  if (cssOut[i]) utilCss.set(k, cssOut[i]);
});
const isClass = (k) => utilCss.has(k) || custom.has(k);

// Tokens used as a class anywhere in a class context.
const ctxClass = new Set();
for (const fr of frags) if (fr.ctx && fr.toks.length && fr.toks.every(isClass)) fr.toks.forEach((k) => ctxClass.add(k));

// A glued token that could be part of a class name (not a URL, path or key).
const looksDyn = (d) => /^(\$\{\})?[a-z!-][\w:\[\].\/-]*(\$\{\})?$/.test(d) && !/[?=&]|^\/|:\/\//.test(d.replace(/\$\{\}/g, "")) && /[-:]/.test(d) && d.replace(/\$\{\}/g, "").split(":").slice(0, -1).every((v) => ds.parseVariant(v));
const strings = new Map(); // classes -> { uses, at }
const uses = new Map(); // class -> count
const dynamic = [];
const unknownInCtx = new Map(); // token -> first location
for (const fr of frags) {
  const at = `${fr.file}:${fr.line}`;
  const { toks } = fr;
  const allCls = toks.length > 0 && toks.every(isClass);
  const plausible = fr.ctx || toks.length >= 2 || toks.some((k) => /[-:[\/]/.test(k)) || toks.every((k) => ctxClass.has(k));
  if (allCls && plausible) {
    const key = toks.join(" ");
    const s = strings.get(key) || { uses: 0, at };
    s.uses++;
    strings.set(key, s);
    for (const k of toks) uses.set(k, (uses.get(k) || 0) + 1);
    // A glued token in a class string is a dynamic class (`text-${tone}`).
    for (const d of fr.dyn) if (looksDyn(d)) dynamic.push([at, d, fr.text.trim()]);
  } else if (fr.ctx) {
    if (toks.every(isClass)) for (const d of fr.dyn) if (looksDyn(d)) dynamic.push([at, d, fr.text.trim()]);
    if (toks.length && toks.filter(isClass).length >= toks.length / 2) {
      // Mostly classes in a class context: the rest are names Tailwind does not know.
      for (const k of toks) if (!isClass(k) && !unknownInCtx.has(k)) unknownInCtx.set(k, at);
      const known = toks.filter(isClass);
      const key = known.join(" ");
      const s = strings.get(key) || { uses: 0, at };
      s.uses++;
      strings.set(key, s);
      for (const k of known) uses.set(k, (uses.get(k) || 0) + 1);
    }
  }
}

// Cross-check against Tailwind's own scanner: every utility it would generate from launcher/src.
const scanner = new Scanner({ sources: [{ base: srcDir, pattern: "**/*", negated: false }] });
const scanned = scanner.scan().filter((c) => !/\.test\./.test(c));
const scannedCss = ds.candidatesToCss(scanned);
const generated = scanned.filter((_, i) => scannedCss[i]);
const missed = generated.filter((c) => !uses.has(c)).sort();

const oneLine = (c) =>
  c
    .replace(/@property[^{]+\{[^}]*\}/g, "")
    .replace(/\s+/g, " ")
    .trim();

fs.mkdirSync(out, { recursive: true });
const sortedStrings = [...strings.entries()].sort((a, b) => (a[0] < b[0] ? -1 : 1));
fs.writeFileSync(
  path.join(out, "strings.tsv"),
  "# uses\tfirst use\tclass string (generated by tools/extract.mjs, do not edit)\n" + sortedStrings.map(([k, s]) => `${s.uses}\t${s.at}\t${k}`).join("\n") + "\n",
);
const sortKey = (c) => {
  if (!utilCss.has(c)) return "-";
  const cand = ds.parseCandidate(c)[0];
  const ps = cand ? ds.compileAstNodes(cand).map((x) => x.propertySort) : [];
  return ps.length ? `${ps[0].order.join(",")};${ps[0].count}` : "-";
};
const sortedClasses = [...uses.entries()].sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1));
fs.writeFileSync(
  path.join(out, "classes.tsv"),
  "# uses\tclass\tsort\tTailwind CSS (generated by tools/extract.mjs, do not edit)\n" + sortedClasses.map(([k, n]) => `${n}\t${k}\t${sortKey(k)}\t${utilCss.has(k) ? oneLine(utilCss.get(k)) : "custom (app.css)"}`).join("\n") + "\n",
);
fs.writeFileSync(path.join(out, "dynamic.tsv"), "# location\tglued token\tfragment\n" + dynamic.map((d) => d.join("\t")).join("\n") + "\n");
fs.writeFileSync(
  path.join(out, "extract.json"),
  JSON.stringify(
    {
      tailwind: require("tailwindcss/package.json").version,
      files: files.length,
      classUses: [...uses.values()].reduce((a, b) => a + b, 0),
      distinctClasses: uses.size,
      classStrings: strings.size,
      dynamic: dynamic.length,
      customClasses: [...custom].sort(),
      unknownInClassContext: Object.fromEntries([...unknownInCtx.entries()].sort()),
      scannerUtilities: generated.length,
      scannerUtilitiesNotInCorpus: missed,
    },
    null,
    1,
  ) + "\n",
);
console.log(
  `${files.length} files, ${[...uses.values()].reduce((a, b) => a + b, 0)} class uses, ${uses.size} distinct classes, ${strings.size} class strings, ${dynamic.length} dynamic, ${missed.length} scanner utilities not in corpus`,
);
